    function getLocale() {
        try {
            var stored = localStorage.getItem(STORAGE_KEY);
            return stored === 'en' || stored === 'vi' ? stored : DEFAULT_LOCALE;
        } catch (e) {
            return DEFAULT_LOCALE;
        }
    }

    function t(key, locale) {
        locale = locale || getLocale();
        var table = dict[locale] || dict[DEFAULT_LOCALE];
        var value = key;
        if (table && Object.prototype.hasOwnProperty.call(table, key)) {
            value = table[key];
        } else {
            var fallback = dict[DEFAULT_LOCALE];
            if (fallback && Object.prototype.hasOwnProperty.call(fallback, key)) value = fallback[key];
        }
        var projectName = (window.APP_CONFIG && window.APP_CONFIG.projectName) || '';
        return value.replace(/\{projectName\}/g, projectName);
    }

    function applyTranslations(locale) {
        locale = locale || getLocale();
        document.documentElement.setAttribute('lang', locale === 'en' ? 'en' : 'vi');

        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            el.textContent = t(el.getAttribute('data-i18n'), locale);
        });
        document.querySelectorAll('[data-i18n-tooltip]').forEach(function (el) {
            el.setAttribute('data-tooltip', t(el.getAttribute('data-i18n-tooltip'), locale));
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'), locale));
        });
        document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
            el.setAttribute('title', t(el.getAttribute('data-i18n-title'), locale));
        });
        document.querySelectorAll('[data-i18n-value]').forEach(function (el) {
            el.value = t(el.getAttribute('data-i18n-value'), locale);
        });
        document.querySelectorAll('[data-locale-active]').forEach(function (el) {
            el.classList.toggle('is-active', el.getAttribute('data-locale-active') === locale);
        });

        document.dispatchEvent(new CustomEvent('localechange', { detail: { locale: locale } }));
    }

    function setLocale(locale) {
        if (locale !== 'vi' && locale !== 'en') return;
        try { localStorage.setItem(STORAGE_KEY, locale); } catch (e) { /* ignore */ }
        applyTranslations(locale);
    }

    window.i18n = {
        t: t,
        getLocale: getLocale,
        setLocale: setLocale,
        apply: applyTranslations,
        dict: dict
    };

    document.addEventListener('DOMContentLoaded', function () {
        applyTranslations(getLocale());
    });
